-- Recebe as respostas de "Esta pagina ajudou voce?" das paginas de conteudo.
--
-- POR QUE ISTA TABELA EXISTE
-- O widget de feedback precisa de um destino. Sem esta tabela ele mostraria
-- "Obrigado pela resposta!" e nao gravaria nada — que e o mesmo defeito que o
-- formulario de caso tinha. Por isso o script vai junto com o widget, e o
-- modulo diz que falhou quando nao tem para onde enviar.
--
-- COMO RODAR: cole no SQL Editor do Supabase e execute. Pode rodar mais de
-- uma vez — tudo aqui usa IF NOT EXISTS / IF EXISTS.
--
-- O QUE GUARDA
--   pagina     qual pagina respondeu (caminho, nao URL com query)
--   resposta   'sim' ou 'nao'
--   comentario texto livre, opcional
--   criado_em  quando chegou
--
-- O QUE NAO GUARDA
--   Nao guarda id de usuario, IP, user-agent, sessao, cookie nem origem do
--   trafego. Nao ha campo para diagnostico, e o widget nao pergunta um.
--   A resposta e anonima por construcao: nao existe como ligar um "nao" a uma
--   pessoa, porque nada que identifique a pessoa e guardado.
--
-- O COMENTARIO E DADO SENSIVEL
-- A pessoa escreve em texto livre e pode, sem querer, colocar ali um
-- diagnostico ou uma situacao pessoal. Por isso:
--   - o campo e opcional e o botao diz que nao e obrigatorio responder;
--   - a pergunta nao induz a pessoa a se descrever;
--   - quem le, le pelo painel com sessao de admin.
--
-- PERMISSAO
-- INSERT liberado para anonimo e autenticado. Nao ha politica de SELECT: a
-- tabela nao aparece pela API publica, nem para anon, nem para autenticado.
-- ============================================================================

CREATE TABLE IF NOT EXISTS public.feedback_pagina (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pagina      text        NOT NULL,
    resposta    text        NOT NULL CHECK (resposta IN ('sim', 'nao')),
    comentario  text,
    criado_em   timestamptz NOT NULL DEFAULT now()
);

-- Como o painel vai ler: os mais recentes primeiro.
CREATE INDEX IF NOT EXISTS feedback_pagina_criado_em_idx
    ON public.feedback_pagina (criado_em DESC);

-- O mesmo comentario de 26/25 vale aqui: sem isto a tabela fica legivel por
-- qualquer chave anon que o site carrega.
ALTER TABLE public.feedback_pagina ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "feedback insert anon" ON public.feedback_pagina;
DROP POLICY IF EXISTS "feedback insert authenticated" ON public.feedback_pagina;
DROP POLICY IF EXISTS "feedback select anon" ON public.feedback_pagina;
DROP POLICY IF EXISTS "feedback select authenticated" ON public.feedback_pagina;
DROP POLICY IF EXISTS "feedback update anon" ON public.feedback_pagina;
DROP POLICY IF EXISTS "feedback delete anon" ON public.feedback_pagina;

CREATE POLICY "feedback insert anon"
    ON public.feedback_pagina FOR INSERT TO anon
    WITH CHECK (true);

CREATE POLICY "feedback insert authenticated"
    ON public.feedback_pagina FOR INSERT TO authenticated
    WITH CHECK (true);

-- Sem politica de SELECT. Quem le, le pelo painel.
