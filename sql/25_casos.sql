-- Tabela que recebe os relatos enviados pelo formulario da pagina de Direitos.
--
-- POR QUE ESTA TABELA EXISTE
-- O formulario "Envie sua situacao" (id="caseForm" em Direitos/direitos.html)
-- recebia nome, e-mail e a descricao da situacao, mostrava "Caso enviado! Nossa
-- equipe vai analisar em breve" e NAO ENVIAVA NADA. O texto digitado era
-- descartado no navegador. Este script cria o destino que faltava.
--
-- COMO RODAR: cole no SQL Editor do Supabase e execute. Pode rodar mais de uma
-- vez — tudo aqui usa IF NOT EXISTS / IF EXISTS.
--
-- O QUE ESTA TABELA GUARDA
--   nome       o que a pessoa digitou
--   email      o que a pessoa digitou, para resposta
--   descricao  o relato, em texto livre
--   origem     qual pagina enviou
--   criado_em  quando chegou
--
-- O QUE ESTA TABELA NAO GUARDA
--   Nao guarda id de usuario, IP, user-agent, sessao nem origem do trafego.
--   Nao ha campo para diagnostico, e o formulario nao pede um. O relato em
--   texto livre e dado sensivel e e a pessoa que decide se escreve.
--
-- PERMISSAO
-- INSERT liberado para anonimo e autenticado. SELECT NAO e liberado a ninguem
-- pela chave anon: quem filtra um relato tem que estar logado como admin e ler
-- pelo painel. Sem politica de SELECT, a tabela nao vaza pela API publica.
-- ============================================================================

CREATE TABLE IF NOT EXISTS public.casos (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        text        NOT NULL,
    email       text        NOT NULL,
    descricao   text        NOT NULL,
    origem      text,
    criado_em   timestamptz NOT NULL DEFAULT now()
);

-- Indice por data: e como o painel vai ler (os mais recentes primeiro).
CREATE INDEX IF NOT EXISTS casos_criado_em_idx ON public.casos (criado_em DESC);

-- Sem isso a tabela fica legivel por qualquer chave que o site carrega.
ALTER TABLE public.casos ENABLE ROW LEVEL SECURITY;

-- Politicas no Postgres somam com OU. As antigas, se existirem, continuam
-- valendo por cima das novas, entao as duas pontas sao limpas antes.
DROP POLICY IF EXISTS "casos insert anon" ON public.casos;
DROP POLICY IF EXISTS "casos insert authenticated" ON public.casos;
DROP POLICY IF EXISTS "casos select anon" ON public.casos;
DROP POLICY IF EXISTS "casos select authenticated" ON public.casos;
DROP POLICY IF EXISTS "casos update anon" ON public.casos;
DROP POLICY IF EXISTS "casos delete anon" ON public.casos;

-- So quem preenche pode enviar. O anon e liberado porque o formulario nao
-- exige login: quem sofre uma violacao raramente tem conta no site.
CREATE POLICY "casos insert anon"
    ON public.casos FOR INSERT TO anon
    WITH CHECK (true);

CREATE POLICY "casos insert authenticated"
    ON public.casos FOR INSERT TO authenticated
    WITH CHECK (true);

-- Nao ha politica de SELECT. Sem ela, a tabela nao aparece na API publica:
-- nem anon, nem autenticado. Quem le, le pelo painel com sessao de admin.
